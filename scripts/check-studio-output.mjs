import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { readFile, stat } from 'node:fs/promises';
import path from 'node:path';
const output = path.resolve(process.argv[2] || 'dist');
const home = await readFile(path.join(output, 'index.html'), 'utf8');
const canonical = home.match(/<link\b[^>]*rel="canonical"[^>]*href="([^"]+)"/)?.[1];
assert.ok(canonical);
const base = new URL(canonical).pathname.replace(/\/$/, '');
const studio = home.indexOf('id="studio"');
const articles = home.indexOf('id="articles"');
assert.ok(studio >= 0 && articles > studio, 'Both the studio and the complete article feed must remain in the homepage');
assert.match(home, /data-home-tabs/, 'The homepage must offer a compact studio/article switcher');
assert.match(home, /data-home-panel="studio"/, 'The studio must remain available as a reading panel');
assert.match(home, /data-home-panel="articles"/, 'Articles must remain available as a reading panel');
assert.match(home, /<dialog\b[^>]*data-home-notebook/, 'Site information must remain available in an independent notebook dialog');
assert.match(home, /data-home-notebook-open/, 'The notebook must have a visible entry beside the article list');
assert.doesNotMatch(home, /class="home-colophon/, 'Site information must not expand into a tall article sidebar');
assert.match(home, /data-studio-details\b[^>]*popover="manual"[^>]*role="dialog"/, 'Object details must have a single accessible popover outside scene clipping');
assert.match(home, /data-studio-auto="true"/, 'The home studio must load automatically');
assert.match(home, /data-studio-navigation="drawer"/, 'Studio objects must open the reading drawer');
assert.match(home, /<dialog\b[^>]*data-studio-drawer/, 'The studio must include an accessible reading window');
assert.match(home, /<iframe\b[^>]*data-drawer-frame/, 'The reading window must preserve interactive page content');
assert.match(home, /data-drawer-resize/, 'The reading window must support resizing');
assert.match(home, /data-drawer-dock/, 'The reading window must support minimizing and restoring');
assert.doesNotMatch(home, /data-avatar-pause/, 'The removed avatar pause button must not appear on the homepage');
const companion = await readFile(path.join(output, 'companion/index.html'), 'utf8');
assert.match(companion, /data-companion-viewer/, 'The car page must use a dedicated full-width model viewer');
assert.doesNotMatch(companion, /companion-story|companion-palette|companion-traits|companion-location/, 'Long prose and ornamental panels must not compete with the model');
for (const html of [home, companion]) {
  assert.match(html, /data-avatar-root[^>]*data-state="loading"[^>]*aria-busy="true"/, 'Car previews must start with the loading presentation');
  assert.match(html, /<button\b[^>]*data-avatar-greet[^>]*\bdisabled/, 'Car interaction must wait for the first rendered frame');
  assert.match(html, /data-avatar-loading-title/, 'Car previews must provide a text loading status');
  assert.match(html, /data-avatar-retry[^>]*\bhidden/, 'An optional retry must be available when model loading fails');
  assert.doesNotMatch(html, /avatar-fallback|当前显示车模插画/, 'The removed simplified car illustration must never flash during loading');
}
assert.doesNotMatch(companion, /companion-model-note|本站进行了几何压缩、材质与展示调整|来源与修改说明/, 'The removed long model note must not appear on the showcase page');
assert.doesNotMatch(companion, /data-avatar-pause/, 'The removed avatar pause button must not appear on the companion page');
assert.match(home, /data-avatar-model="mercedes-g-class"/, 'The welcome card must display the G-Class car model');
assert.match(companion, /data-avatar-model="mercedes-g-class"/, 'The enlarged preview must use the same car model');
assert.doesNotMatch(home + companion, /小渡|小信使/, 'Robot labels must not remain in the car presentation');
assert.ok(companion.includes(`${base}/models/mercedes-g63-amg.glb`), 'The enlarged preview must offer the imported car download');
assert.ok(home.includes(`${base}/models/mercedes-g63-amg.glb`), 'The welcome card must load the imported local GLB');
assert.match(home + companion, /pranav27/, 'The creator must be credited wherever the model is displayed');
assert.match(companion, /CC BY 4\.0/, 'The imported model must retain a visible license credit');
assert.doesNotMatch(home + companion, /data-avatar-action="doors"|打开前车门|棕色座椅/, 'The static source must not promise an unsupported door animation or interior');
const notice = await readFile(path.join(output, 'models/mercedes-g63-amg.LICENSE.txt'), 'utf8');
assert.match(notice, /pranav27/);
assert.match(notice, /CC BY 4\.0/);
const car = await readFile(path.join(output, 'models/mercedes-g63-amg.glb'));
assert.equal(createHash('sha256').update(car).digest('hex'), '4fec52ebf5c009cdf8a867bb5d8bb24dbb8a4464223f9d6a40312ba8231034d7', 'The published car must match the unmodified author download');
for (const html of [home, companion]) assert.ok(html.includes('mercedes-g63-amg.glb?v=original-4fec52ebf5c0'), 'Both car previews must invalidate the previous compressed model cache');
assert.doesNotMatch(home, /data-studio-enter/, 'The home experience must not require an enter button');
assert.match(home, /class="landing-scroll" href="#studio"/, 'The welcome scroll cue must point into the studio');
const destinations = [...home.matchAll(/<a\b([^>]*\bdata-studio-destination="([^"]+)"[^>]*)>/g)];
assert.deepEqual(destinations.map(([, , id]) => id).sort(), ['about', 'ai', 'archive', 'bim', 'contact', 'notes']);
for (const [, attributes, id] of destinations) {
    const href = attributes.match(/\bhref="([^"]+)"/)?.[1];
    assert.ok(href, `${id} must remain a real link without JavaScript or WebGL`);
    assert.match(attributes, /aria-haspopup="dialog"/, `${id} must identify its content window`);
    assert.match(attributes, /aria-controls="studio-object-details"/, `${id} must identify the object details`);
    const url = new URL(href, canonical);
    assert.equal(url.origin, new URL(canonical).origin, `${id} must lead to a blog destination`);
    assert.ok(url.pathname.startsWith(`${base}/`), 'Studio link has the wrong deployment base');
    const relative = decodeURIComponent(url.pathname.slice(base.length)).replace(/^\/+|\/+$/g, '');
    const target = await readFile(path.join(output, relative, 'index.html'), 'utf8');
    if (url.hash)
        assert.ok(target.includes(`id="${decodeURIComponent(url.hash.slice(1))}"`), `${id} has a missing section anchor`);
}
const model = await stat(path.join(output, 'models/moon-bay-studio.glb'));
assert.ok(model.size > 0);
console.log('Verified compact home panels, independent notebook dialog, object detail popover, six fallback links, automatic 3D, reading window controls and model asset.');
